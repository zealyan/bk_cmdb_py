def is_mongo_available():
    """检查数据库是否可用"""
    try:
        conn = get_db_connection()
        if conn is not None:
            if use_mongomock:
                return True
            # 真实 MongoDB 的检查方式
            client.admin.command('ping')
            return True
        return False
    except Exception as e:
        print(f"MongoDB 可用性检查失败: {e}")
        return False


